function t(key, vars) {
  const lang = (typeof S !== 'undefined' && S.settings.promptLang) || 'ru';
  const row = I18N[key];
  let s = lang === 'ru' || !row ? key : row[lang === 'en' ? 0 : 1];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(v);
  return s;
}

// Static markup in index.html: data-i18n="<russian>" sets the text,
// data-i18n-title / data-i18n-ph set the title / placeholder.
function applyStaticI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); el.setAttribute('aria-label', el.title); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.documentElement.lang = S.settings.promptLang || 'ru';
}
